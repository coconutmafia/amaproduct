// Цвет текста и фона ПЛАШКИ — одно правило для превью (FreeCanvas) и сервера
// (engine FreeLines/StoryText). Разъезд этих двух мест уже стоил нам класса
// багов с переносом строк (см. lib/carousel/textLayout), поэтому правило живёт
// здесь, а не дублируется в компонентах.
//
// 09.09 (Светлана Кундаль): «не удаётся поменять цвет шрифта — тыкаешь на
// цветные кружочки, не меняется». Причина: на плашке цвет текста ВСЕГДА брался
// из темы, а выбранный цвет применялся только к тексту без плашки. Замерено на
// проде: клик по зелёному кружку → computed color остаётся rgb(255,255,255).
// Теперь выбранный явно цвет (colorSet) применяется и на плашке; без флага —
// прежнее поведение, поэтому сохранённые ранее оформления не меняются.

export interface PlateStyleInput {
  color?: string
  /** цвет выбран человеком явно (клик по палитре), а не остался с создания блока */
  colorSet?: boolean
  /** цвет самой плашки; без него — фон темы */
  plateColor?: string
}

/** Цвет текста НА ПЛАШКЕ: явный выбор человека, иначе цвет темы. */
export function plateTextColor(b: PlateStyleInput, themeText: string): string {
  return b.colorSet && b.color ? b.color : themeText
}

/** Фон плашки: выбранный цвет, иначе фон темы (как было). */
export function plateBackground(b: PlateStyleInput, themeBg: string): string {
  return b.plateColor || themeBg
}
