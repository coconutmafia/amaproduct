// Проверочный проход ответа ассистента («факт-чек»), 07.09.
//
// A/B №4 (12 вопросов × 2 проекта, слепой судья по материалам): черновик Opus 5
// против того же черновика после проверки вторым вызовом по тем же материалам —
// 12:0 в пользу проверки, балл 19,8 против 17,2 из 20, выдумок 1 против 27.
// Правила дословности в промпте дали 5:4 и 7 против 10 выдумок, глубина xhigh —
// ничего, Fable 5.1 — ничего при +86% цены. Выдумки прода — три типа: чужая
// атрибуция реальной цитаты, придуманные цифры, несуществующие цитаты; это
// «заполнение пробела», и его ловит именно сверка готового текста с материалами.
//
// Механика: черновик стримится как раньше, затем сервер шлёт МАРКЕР и стримит
// исправленный текст (тот же кэш-префикс материалов → чтение 0,1×, доплата ≈
// вход черновика + выход). Клиент, увидев маркер, показывает «сверяю факты» и по
// окончании подменяет черновик проверенным. Проверка не удалась / пустая →
// остаётся черновик (маркер без хвоста = «без изменений»).
// Этот модуль чистый (без server-only импортов): его читают и роут, и страницы.

export const FACTCHECK_MARKER = '\n\n⁣[[факт-чек]]⁣\n'

export const FACTCHECK_STATUS = '\n\n🔎 Сверяю факты с материалами…'

/** Минимальная длина черновика, при которой проверка имеет смысл. */
export const FACTCHECK_MIN_CHARS = 300

/** Разбор стрима: черновик до маркера, проверенный текст после. */
export function splitFactcheck(acc: string): { draft: string; checked: string | null } {
  const i = acc.indexOf(FACTCHECK_MARKER)
  if (i < 0) return { draft: acc, checked: null }
  return { draft: acc.slice(0, i), checked: acc.slice(i + FACTCHECK_MARKER.length) }
}

/** Что показывать во время стрима: черновик, а после маркера — черновик + статус. */
export function streamingDisplay(acc: string): string {
  const { draft, checked } = splitFactcheck(acc)
  if (checked === null) return draft
  return draft + FACTCHECK_STATUS
}

/**
 * Итоговый текст ответа: проверенный, если он пришёл и не «сдулся» (обрыв
 * проверки на первых строках не должен заменить целый черновик), иначе черновик.
 */
export function finalAnswer(acc: string): string {
  const { draft, checked } = splitFactcheck(acc)
  if (checked === null) return draft
  const c = checked.trim()
  if (c.length < Math.min(draft.trim().length * 0.5, 200)) return draft
  return c
}

/** Промпт проверки — тот же, что выиграл A/B №4 (scripts/context-ab4.mjs, VERIFY). */
export function factcheckPrompt(question: string, draft: string): string {
  return `Ты — редактор-фактчекер этого же проекта. Ниже ВОПРОС и ЧЕРНОВИК ответа ассистента. Сверь каждый факт черновика с материалами проекта выше (и с фрагментами в вопросе):
— цитата не дословная или приписана не тому источнику/человеку → исправь на дословную из материалов или сними имя («одна из участниц кастдева»); если такой цитаты нет вообще — убери её;
— цифра, которой нет в материалах, или взята из другого контекста → убери цифру или замени на ту, что есть;
— деталь о продукте/методе/кейсе/человеке, которой нет в материалах → убери или перепиши без домысла.
Стиль, структуру и голос черновика сохрани; не добавляй новых утверждений. Верни ТОЛЬКО исправленный ответ целиком, без пояснений и пометок.

=== ВОПРОС ===
${question}

=== ЧЕРНОВИК ===
${draft}`
}
