-- 050: почта плательщика, отличная от почты аккаунта (07.09.2026, Виктория).
--
-- Продамус открывает СВОЮ форму, и плательщик вводит почту руками (или браузер
-- подставляет прошлую). Первичный платёж теперь привязывается по нашему номеру
-- заказа (order_num), но РЕКУРРЕНТЫ приходят с почтой плательщика, а
-- subscription.id у Продамуса — id продукта, общий у многих. Поэтому владелец
-- хранит почту плательщика здесь; вебхук ищет по email ИЛИ billing_email.
-- Код живёт без колонки (вебхук глотает 42703), миграция только добавляет поиск.
alter table profiles add column if not exists billing_email text;
create index if not exists profiles_billing_email_idx on profiles (lower(billing_email));
