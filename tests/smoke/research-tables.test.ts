import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { audienceResearchToAoa, audienceResearchToPivotAoa, meaningsMapToAoa } from '@/lib/researchTables'

// Фикстуры сняты с РЕАЛЬНОГО прод-формата 31 июля (мастер «Общая таблица
// кастдевов» + отдельная «Таблица исследования»). Регрессия, которую ловим:
// мастер разделяет интервью заголовками «═══ Кастдев …» без "---", и старый
// парсер слеплял ВСЕ интервью в одну строку первого участника (файл Матвея:
// 2 строки × 99 колонок). Плюс вложенные скобки в сегменте («живёт в Москве
// (Россия)») и имя со скобками («Игорь (Егор)»).

const MASTER = `═══ Кастдев от 27 июля ═══

Участник: Участник 1 (Женщина 30+, г. Волжский, преподаёт танцы ~10 лет)

  Вопрос: Расскажи о себе
  Ответ: Это 30+. Город Волжский.
Преподаю лет 10.
  Цитаты: опыт большой | танцую тоже лет 10
  Тон: нейтрально

  Вопрос: Где преподаёшь
  Ответ: В фитнес-студии.
  Цитаты: работаю на проценте
  Тон: гордость

═══ Кастдев от 28 июля ═══

Участник: Игорь (Егор) (Мужчина, 40 лет, живёт в Москве (Россия), предприниматель)

  Вопрос: Расскажи о себе
  Ответ: Мне сорок лет.
  Цитаты: много ответственности
  Тон: усталость
`

const INDIVIDUAL = `Участник: Лиза (Женщина, 22 года, Москва)

  Вопрос: Расскажи о себе
  Ответ: Танцую 19 лет.
  Цитаты: преподаю 4-й год
  Тон: воодушевление
---
Участник: Катя (Женщина, 19 лет, Саранск)

  Вопрос: Расскажи о себе
  Ответ: Танцую с 4 лет.
  Цитаты: 4 группы
  Тон: нейтрально
`

describe('audienceResearchToAoa — вертикальная таблица', () => {
  it('мастер: каждый кастдев и участник — свои строки, ничего не слипается', () => {
    const aoa = audienceResearchToAoa(MASTER)
    expect(aoa[0]).toEqual(['Кастдев', 'Участник', 'Сегмент', 'Вопрос', 'Ответ', 'Цитаты', 'Тон'])
    expect(aoa.length).toBe(1 + 3) // 3 вопрос-ответа
    const participants = new Set(aoa.slice(1).map((r) => r[1]))
    expect(participants).toEqual(new Set(['Участник 1', 'Игорь (Егор)']))
    expect(aoa[1][0]).toBe('Кастдев от 27 июля')
    expect(aoa[3][0]).toBe('Кастдев от 28 июля')
  })

  it('многострочный ответ склеивается, цитаты и тон на месте', () => {
    const aoa = audienceResearchToAoa(MASTER)
    expect(aoa[1][4]).toBe('Это 30+. Город Волжский.\nПреподаю лет 10.')
    expect(aoa[1][5]).toBe('опыт большой | танцую тоже лет 10')
    expect(aoa[2][6]).toBe('гордость')
  })

  it('вложенные скобки: имя «Игорь (Егор)», сегмент с «(Россия)» внутри', () => {
    const aoa = audienceResearchToAoa(MASTER)
    const row = aoa.find((r) => r[1] === 'Игорь (Егор)')!
    expect(row[2]).toBe('Мужчина, 40 лет, живёт в Москве (Россия), предприниматель')
  })

  it('отдельная таблица (без ═══): нет колонки «Кастдев», участники по ---', () => {
    const aoa = audienceResearchToAoa(INDIVIDUAL)
    expect(aoa[0]).toEqual(['Участник', 'Сегмент', 'Вопрос', 'Ответ', 'Цитаты', 'Тон'])
    expect(aoa.length).toBe(1 + 2)
    expect(aoa[1][0]).toBe('Лиза')
    expect(aoa[2][0]).toBe('Катя')
  })

  it('пустой/чужой текст — пустой результат, не мусорная строка', () => {
    expect(audienceResearchToAoa('просто текст без структуры')).toEqual([])
  })
})

describe('audienceResearchToPivotAoa — сводка «как в уроке»', () => {
  it('строка = участник, колонки = вопросы, ответы по местам', () => {
    const aoa = audienceResearchToPivotAoa(MASTER)
    expect(aoa[0]).toEqual(['Кастдев', 'Участник', 'Сегмент', 'Расскажи о себе', 'Где преподаёшь'])
    expect(aoa.length).toBe(1 + 2) // 2 участника
    const p1 = aoa[1]
    expect(p1[1]).toBe('Участник 1')
    expect(p1[3]).toContain('Город Волжский')
    expect(p1[4]).toContain('В фитнес-студии')
    const p2 = aoa[2]
    expect(p2[1]).toBe('Игорь (Егор)')
    expect(p2[4]).toBe('') // на второй вопрос не отвечал
  })

  it('одноимённые участники разных кастдевов не слипаются', () => {
    const two = `═══ Кастдев от 1 июля ═══\n\nУчастник: Аня (сегмент А)\n\n  Вопрос: В1\n  Ответ: раз\n\n═══ Кастдев от 2 июля ═══\n\nУчастник: Аня (сегмент Б)\n\n  Вопрос: В1\n  Ответ: два\n`
    const aoa = audienceResearchToPivotAoa(two)
    expect(aoa.length).toBe(1 + 2)
  })

  // Файл Дарьи (11 августа): «Насколько физкультура соответствует ценностям
  // организации?» и без «?» были ДВУМЯ колонками — ответы участниц лежали
  // врозь, таблица выглядела пустой. Пунктуация/регистр/ё и полный префикс
  // («…по шкале») сливаются; РАЗНЫЕ вопросы — нет.
  it('вариации одного вопроса (пунктуация/регистр/хвост-уточнение) — одна колонка', () => {
    const text = [
      '═══ Кастдев от 1 июля ═══', '',
      'Участник: Аня (педагог)', '',
      '  Вопрос: Насколько физкультура соответствует ценностям организации?',
      '  Ответ: полностью', '',
      '═══ Кастдев от 2 июля ═══', '',
      'Участник: Ира (методист)', '',
      '  Вопрос: насколько физкультура соответствует ценностям организации',
      '  Ответ: частично', '',
      '  Вопрос: Насколько физкультура соответствует ценностям организации по шкале от 1 до 10',
      '  Ответ: на семь', '',
      '  Вопрос: Как устроена двигательная среда?',
      '  Ответ: по-разному',
    ].join('\n')
    const aoa = audienceResearchToPivotAoa(text)
    // Колонки: Кастдев | Участник | Сегмент | вопрос-про-ценности | вопрос-про-среду
    expect(aoa[0].length).toBe(5)
    const anya = aoa.find((r) => r[1] === 'Аня')!
    const ira = aoa.find((r) => r[1] === 'Ира')!
    expect(anya[3]).toBe('полностью')
    expect(ira[3]).toBe('частично') // первая вариация участника побеждает
    expect(ira[4]).toBe('по-разному')
  })

  it('разные по смыслу вопросы не сливаются (не префиксы друг друга)', () => {
    const text = [
      'Участник: Аня (педагог)', '',
      '  Вопрос: Как устроена физкультура в организации?',
      '  Ответ: системно', '',
      '  Вопрос: Как устроена физкультура в детском саду?',
      '  Ответ: игрово',
    ].join('\n')
    const aoa = audienceResearchToPivotAoa(text)
    expect(aoa[0].length).toBe(2 + 2) // Участник | Сегмент | два РАЗНЫХ вопроса
  })
})

describe('meaningsMapToAoa — шапка из урока «Карта смыслов»', () => {
  it('старый формат (одна строка на категорию) читается по-прежнему', () => {
    const aoa = meaningsMapToAoa('[PAIN] Устала:\nФормулировки: я устала\nИдея контента: пост про отдых')
    expect(aoa[0]).toEqual(['Категория', 'Общая формулировка', 'Формулировка клиента', 'Идеи контента'])
    expect(aoa[1]).toEqual(['Боли', 'Устала', 'я устала', 'пост про отдых'])
  })

  // Новый формат (3 августа, строго по уроку): формулировка каждого клиента =
  // отдельная строка, у каждой своя идея контента. Пример «я толстая» из урока.
  it('новый формат: строка на каждую формулировку клиента со своей идеей', () => {
    const text = [
      '[БОЛИ] Я толстая',
      '— «чувствую себя неуверенно в своем теле и имею лишние килограммы»',
      '  Идея контента: экспертный разбор, как правильно худеть',
      '— «я поправилась после родов и никак не могу похудеть»',
      '  Идея контента: кейс Карины, которая похудела после родов',
      '',
      '[ХОТЕЛКИ, ПОТРЕБНОСТИ] Хочу быть стройной',
      '— «хочу влезть в старые джинсы»',
      '  Идея контента: метод трёх правил стабильного веса',
    ].join('\n')
    const aoa = meaningsMapToAoa(text)
    expect(aoa[0]).toEqual(['Категория', 'Общая формулировка', 'Формулировка клиента', 'Идеи контента'])
    expect(aoa[1]).toEqual(['Боли', 'Я толстая', 'чувствую себя неуверенно в своем теле и имею лишние килограммы', 'экспертный разбор, как правильно худеть'])
    expect(aoa[2]).toEqual(['Боли', 'Я толстая', 'я поправилась после родов и никак не могу похудеть', 'кейс Карины, которая похудела после родов'])
    expect(aoa[3]).toEqual(['Хотелки, Потребности', 'Хочу быть стройной', 'хочу влезть в старые джинсы', 'метод трёх правил стабильного веса'])
  })

  // Порядок категорий = слайд видеоурока «СТОЛБЕЦ 1. КАТЕГОРИЯ»:
  // Боли → Хотелки, Потребности → Триггеры → Возражения → Ваши преимущества.
  it('категории сортируются в порядке слайда урока', () => {
    const text = [
      '[ВАШИ ПРЕИМУЩЕСТВА] Системность',
      '— «у тебя всё по шагам»',
      '  Идея контента: показать структуру программы',
      '',
      '[ВОЗРАЖЕНИЯ] Дорого',
      '— «пока не готова столько платить»',
      '  Идея контента: разложить окупаемость',
      '',
      '[ХОТЕЛКИ, ПОТРЕБНОСТИ] Хочу поток',
      '— «хочу заявки из блога»',
      '  Идея контента: кейс запуска',
      '',
      '[БОЛИ] Выгорание',
      '— «работаю на износ»',
      '  Идея контента: личная история про отдых',
    ].join('\n')
    const aoa = meaningsMapToAoa(text)
    expect(aoa[1][0]).toBe('Боли')
    expect(aoa[2][0]).toBe('Хотелки, Потребности')
    expect(aoa[3][0]).toBe('Возражения')
    expect(aoa[4][0]).toBe('Ваши преимущества')
  })

  it('карты со старыми метками (3 августа, до сверки по видео) читаются', () => {
    expect(meaningsMapToAoa('[ПОТРЕБНОСТИ И ХОТЕЛКИ] Хочу поток\n— «хочу заявки из блога»\n  Идея контента: кейс запуска')[1][0]).toBe('Хотелки, Потребности')
    expect(meaningsMapToAoa('[ХОТЕЛКИ/ПОТРЕБНОСТИ] Хочу поток\n— «хочу заявки»\n  Идея контента: кейс')[1][0]).toBe('Хотелки, Потребности')
    expect(meaningsMapToAoa('[ПРЕИМУЩЕСТВА] Системность\n— «всё по шагам»\n  Идея контента: структура')[1][0]).toBe('Ваши преимущества')
  })
})

