import { describe, it, expect } from 'vitest'
import { audienceResearchToAoa } from '@/lib/researchTables'

// Фикстуры сняты с РЕАЛЬНОГО прод-формата 31 июля (мастер «Общая таблица
// кастдевов» + отдельная «Таблица исследования»). Регрессия, которую ловим:
// мастер разделяет интервью заголовками «═══ Кастдев …» без "---", и старый
// парсер слеплял ВСЕ интервью в одну строку первого участника (файл Матвея:
// 2 строки × 99 колонок). Плюс вложенные скобки в сегменте («живёт в Москве
// (Россия)») и имя со скобками («Игорь (Егор)»).

const MASTER = `═══ Кастдев от 27 июля ═══

Участник: Участник 1 (Женщина 30+, г. Волжский, преподаёт танцы ~10 лет)

  Вопрос: Расскажи о себе
  Ответ: Это 30+. Город Волжский.
Преподаю лет 10.
  Цитаты: опыт большой | танцую тоже лет 10
  Тон: нейтрально

  Вопрос: Где преподаёшь
  Ответ: В фитнес-студии.
  Цитаты: работаю на проценте
  Тон: гордость

═══ Кастдев от 28 июля ═══

Участник: Игорь (Егор) (Мужчина, 40 лет, живёт в Москве (Россия), предприниматель)

  Вопрос: Расскажи о себе
  Ответ: Мне сорок лет.
  Цитаты: много ответственности
  Тон: усталость
`

const INDIVIDUAL = `Участник: Лиза (Женщина, 22 года, Москва)

  Вопрос: Расскажи о себе
  Ответ: Танцую 19 лет.
  Цитаты: преподаю 4-й год
  Тон: воодушевление
---
Участник: Катя (Женщина, 19 лет, Саранск)

  Вопрос: Расскажи о себе
  Ответ: Танцую с 4 лет.
  Цитаты: 4 группы
  Тон: нейтрально
`

describe('audienceResearchToAoa — вертикальная таблица', () => {
  it('мастер: каждый кастдев и участник — свои строки, ничего не слипается', () => {
    const aoa = audienceResearchToAoa(MASTER)
    expect(aoa[0]).toEqual(['Кастдев', 'Участник', 'Сегмент', 'Вопрос', 'Ответ', 'Цитаты', 'Тон'])
    expect(aoa.length).toBe(1 + 3) // 3 вопрос-ответа
    const participants = new Set(aoa.slice(1).map((r) => r[1]))
    expect(participants).toEqual(new Set(['Участник 1', 'Игорь (Егор)']))
    expect(aoa[1][0]).toBe('Кастдев от 27 июля')
    expect(aoa[3][0]).toBe('Кастдев от 28 июля')
  })

  it('многострочный ответ склеивается, цитаты и тон на месте', () => {
    const aoa = audienceResearchToAoa(MASTER)
    expect(aoa[1][4]).toBe('Это 30+. Город Волжский.\nПреподаю лет 10.')
    expect(aoa[1][5]).toBe('опыт большой | танцую тоже лет 10')
    expect(aoa[2][6]).toBe('гордость')
  })

  it('вложенные скобки: имя «Игорь (Егор)», сегмент с «(Россия)» внутри', () => {
    const aoa = audienceResearchToAoa(MASTER)
    const row = aoa.find((r) => r[1] === 'Игорь (Егор)')!
    expect(row[2]).toBe('Мужчина, 40 лет, живёт в Москве (Россия), предприниматель')
  })

  it('отдельная таблица (без ═══): нет колонки «Кастдев», участники по ---', () => {
    const aoa = audienceResearchToAoa(INDIVIDUAL)
    expect(aoa[0]).toEqual(['Участник', 'Сегмент', 'Вопрос', 'Ответ', 'Цитаты', 'Тон'])
    expect(aoa.length).toBe(1 + 2)
    expect(aoa[1][0]).toBe('Лиза')
    expect(aoa[2][0]).toBe('Катя')
  })

  it('пустой/чужой текст — пустой результат, не мусорная строка', () => {
    expect(audienceResearchToAoa('просто текст без структуры')).toEqual([])
  })
})
